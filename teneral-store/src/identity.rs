//! The store's own identity.

use std::fmt;

use rusqlite::{Connection, params};

use crate::actor::Actor;
use crate::error::{Error, Result};
use crate::ops;

/// A store's epoch: the half of a cursor that says whose sequence
/// numbers a consumer is holding.
///
/// It is generated when the database is created, and the only thing
/// that changes it afterwards is an operator minting a new one --
/// which is what makes a store restored from a backup honestly a
/// different store. A different epoch is how a consumer learns that
/// the sequence numbers it remembers cannot be continued, and that it
/// must start again from a snapshot rather than resume. A consumer
/// comparing epochs should treat the value as opaque: it is hex today
/// and its only contract is that two stores do not share one, and
/// that one store does not reuse one.
///
/// A type of its own rather than a `String`, because it travels
/// alongside network names and resource identities, and a mix-up
/// between those is exactly the kind of thing that type checks for
/// free.
#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub struct Epoch(String);

impl Epoch {
    /// The epoch as it is written on the wire and in a log.
    pub fn as_str(&self) -> &str {
        &self.0
    }

    /// The epoch half of a position a caller presented, which may
    /// belong to no store at all.
    ///
    /// Crate-private: what is public is [`crate::Cursor::presented`],
    /// which is the only reason an epoch is ever assembled from a
    /// string a caller handed over, and whose documentation carries
    /// why that is safe to offer. Nothing reachable from outside this
    /// crate can make an epoch a store will then *issue* positions in,
    /// so "two stores do not share an epoch" stays true by
    /// construction.
    pub(crate) fn presented(value: &str) -> Self {
        Self(value.to_owned())
    }

    /// An epoch with a value a test chose.
    ///
    /// Every epoch a store issues positions in comes from the engine
    /// when the database is created; this and the constructor above
    /// are the two that are not, and neither can be stored.
    #[cfg(test)]
    pub(crate) fn for_test(value: &str) -> Self {
        Self(value.to_owned())
    }
}

impl fmt::Display for Epoch {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

/// What the store says about itself.
///
/// Three values together rather than three questions, because they
/// are read for one purpose: to decide whether this store is the one
/// a remembered position belongs to, and, when it is not, to say who
/// made it a different one and when. Read separately they could
/// describe two states of the file.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct StoreIdentity {
    /// The epoch every position this store issues is in.
    pub epoch: Epoch,
    /// The actor that minted that epoch, as it was recorded.
    ///
    /// A string rather than an [`Actor`], because an actor is
    /// rendered for a person to read and is never parsed back: a
    /// parser here could disagree with the renderer and make an old
    /// row unreadable. The value for a store whose epoch nobody has
    /// minted says so in a word, and no rendered actor can be
    /// mistaken for it.
    pub minted_by: String,
    /// When it was minted, in seconds since the Unix epoch, or `None`
    /// for the one the database was created with.
    ///
    /// `None` is a fact rather than a missing value: that epoch was
    /// generated by the migration that made the file, so no actor
    /// minted it and nothing recorded an instant for it. A zero here
    /// would be an instant in 1970 and would make "this store has
    /// never been minted" unaskable.
    pub minted_at: Option<i64>,
}

/// Read what the store says about itself.
///
/// The identity row is written by the first migration and there is
/// exactly one, for the reason given on the epoch read below, so an
/// absent row gets the same kind of complaint here.
pub(crate) fn read_identity(conn: &Connection) -> Result<StoreIdentity> {
    let row = conn
        .query_row(
            "SELECT epoch, minted_by, minted_at FROM store_identity WHERE id = 1",
            [],
            |row| {
                Ok((
                    row.get::<_, String>(0)?,
                    row.get::<_, String>(1)?,
                    row.get::<_, Option<i64>>(2)?,
                ))
            },
        )
        .map(Some)
        .or_else(|error| match error {
            rusqlite::Error::QueryReturnedNoRows => Ok(None),
            other => Err(Error::storage("reading the store's identity", other)),
        })?;

    match row {
        Some((epoch, minted_by, minted_at)) => Ok(StoreIdentity {
            epoch: Epoch(epoch),
            minted_by,
            minted_at,
        }),
        None => Err(Error::Malformed {
            detail: "it has no identity row, so there is nothing it can say about itself"
                .to_owned(),
        }),
    }
}

/// Read the epoch the database issues its positions in.
///
/// The identity row is written by the first migration, so a database
/// that has been migrated has exactly one -- the table's primary key
/// and its CHECK constraint together make a second row impossible.
/// An absent row therefore means the file is not a store that this
/// code built, which is worth a distinct complaint rather than an
/// empty answer.
pub(crate) fn read_epoch(conn: &Connection) -> Result<Epoch> {
    let epoch: Option<String> = conn
        .query_row("SELECT epoch FROM store_identity WHERE id = 1", [], |row| {
            row.get(0)
        })
        .map(Some)
        .or_else(|error| match error {
            rusqlite::Error::QueryReturnedNoRows => Ok(None),
            other => Err(Error::storage("reading the store's epoch", other)),
        })?;

    match epoch {
        Some(epoch) => Ok(Epoch(epoch)),
        None => Err(Error::Malformed {
            detail: "it has no identity row, so no epoch to continue a cursor from".to_owned(),
        }),
    }
}

/// Replace the store's epoch, and say which position the new order
/// starts at.
///
/// The value is generated by the engine, in the same expression the
/// first migration uses, so that an epoch has exactly one way of
/// coming into being however many callers want one.
///
/// The position is read inside the same transaction as the update,
/// and that is the point of the transaction: the two halves of the
/// cursor this returns have to describe one state of the file. One
/// store serialises its own writes on one thread, but a second
/// connection to the same file does not go through that thread, and
/// a position read after the update had committed could be one such
/// a write had already moved past -- leaving the first cursor of the
/// new order naming a position the new order did not start at.
///
/// The actor and the instant are written in the same statement as the
/// epoch, as every other attribution in this store is. A write whose
/// attribution could fail separately is one whose attribution is
/// sometimes absent, and a row that says who replaced the epoch only
/// most of the time is a row nobody can read the answer off.
///
/// The sequence counter is deliberately left alone. Restarting it
/// would make a position from the old order and one from the new
/// indistinguishable to anything that compared sequences, which is
/// exactly what the log's `AUTOINCREMENT` high-water mark exists to
/// prevent one layer down.
pub(crate) fn mint_epoch(conn: &mut Connection, actor: &Actor, now: i64) -> Result<(Epoch, u64)> {
    let transaction = conn
        .transaction()
        .map_err(|error| Error::storage("starting a transaction to mint an epoch", error))?;

    let minted: String = transaction
        .query_row(
            "UPDATE store_identity
                SET epoch = lower(hex(randomblob(16))),
                    minted_by = ?1,
                    minted_at = ?2
              WHERE id = 1
             RETURNING epoch",
            params![actor.as_recorded(), now],
            |row| row.get(0),
        )
        .map_err(|error| match error {
            rusqlite::Error::QueryReturnedNoRows => Error::Malformed {
                detail: "it has no identity row, so there is no epoch to replace".to_owned(),
            },
            other => Error::storage("minting an epoch", other),
        })?;

    let position = ops::snapshot_position(&transaction)?;

    transaction
        .commit()
        .map_err(|error| Error::storage("committing a minted epoch", error))?;

    Ok((Epoch(minted), position))
}
