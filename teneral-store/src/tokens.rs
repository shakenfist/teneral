//! Tokens: the credentials a consumer presents, and the statements
//! that mint, remove, list and verify them.
//!
//! A token is not a [`crate::BindingStore`] resource and its
//! mutations are not events in the store's history. Both of those are
//! deliberate, and the reasoning matters more than the rule, because
//! the obvious arrangement is to put tokens where every other
//! resource is and it damages something either way it is tried.
//!
//! A token is store-global. Its answer *is* which networks may be
//! touched, so there is no network to ask it within -- the same shape
//! as the one read in `BindingStore` whose answer is a network. Every
//! other resource there takes the network it applies to as a
//! parameter, and a trait method that could not would be the shape
//! that rule exists to forbid.
//!
//! Forcing one in anyway means forcing a network on to the event the
//! mutation would emit, and the event log's network column is not
//! nullable. Three ways to produce one were considered. A sentinel
//! network name collides with a real network, because names here are
//! opaque and `*` is a legal name. A nullable column breaks the
//! assumption every reader of the log makes, including the index that
//! scopes a network's history. And a token mutation that returned a
//! position without appending an event would be a write claiming a
//! place in an order it is not in -- which is precisely the shape the
//! store's own gate refuses, for the reason that a history silently
//! missing a change is worse than a change that was refused.
//!
//! So tokens have a trait of their own, their mutations return no
//! cursor, and their audit is the row itself: who minted it, when,
//! and when it was last used. That is also a better audit for the
//! thing being audited. Nobody watches the token list as a mirror,
//! so there is no consumer for a token event; what an operator asks
//! is "what credentials exist and when was this one last used", and
//! a row answers that where a stream of past mutations would have to
//! be replayed to.
//!
//! The secret never exists in the database. It is generated by the
//! engine, hashed here, and the hash is what is stored; verification
//! hashes what was presented and looks the hash up, so the plaintext
//! never reaches a comparison and no layer above this one holds any
//! hashing logic.

