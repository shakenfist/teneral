/// What the store calls a token when it has to say so to a person.
const TOKEN: &str = "token";

/// A token's identity, as the store issued it.
///
/// Sixteen random bytes from the engine, as lower-case hex, generated
/// at the instant the token is minted. Opaque: its only contract is
/// that two tokens do not share one, which is what lets it stand in
/// for the token in an attribution that outlives the token itself.
///
/// A type of its own rather than a `String` because it travels beside
/// network names, resource identities and the secret, and a mix-up
/// between any two of those is the kind of thing a type checks for
/// free. There is deliberately no public constructor: every id comes
/// from a mint, so "two tokens do not share an id" is true by
/// construction rather than by nobody having written the constructor
/// that breaks it.
#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub struct TokenId(String);

impl TokenId {
    /// The id as it is written in a listing, a log, and the actor
    /// recorded against every write this token makes.
    pub fn as_str(&self) -> &str {
        &self.0
    }

    /// The id a caller named a credential by.
    ///
    /// Not a way to make a credential. This is how a caller says
    /// *which* one it means, and the only operations that take one
    /// look it up -- an id no credential holds is reported as not
    /// found, and one the caller may not reach is refused for the
    /// scope, both of them answers about an id the caller supplied
    /// itself. Every id a credential actually has still comes from a
    /// mint, which is what keeps "two tokens do not share an id" true
    /// by construction.
    pub fn presented(value: &str) -> Self {
        Self(value.to_owned())
    }

    /// An id with a value a test chose.
    #[cfg(test)]
    pub(crate) fn for_test(value: &str) -> Self {
        Self(value.to_owned())
    }
}

impl fmt::Display for TokenId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

/// Something a token may do.
///
/// Four, and the fourth is the one worth explaining. `Read`, `Write`
/// and `Watch` are the three kinds of thing a consumer does with the
/// resources in the networks it may reach. `Admin` is the operator's
/// own operations -- minting and removing tokens, listing them,
/// minting an epoch -- which are gated by a capability on a token
/// rather than by a separate listener whose file mode the kernel
/// enforces. That makes the strongest boundary in the design a
/// comparison rather than a permission check in the filesystem, which
/// is why the rule that a token may only ever mint downwards is
/// enforced here in the store and not only in whatever calls it.
///
/// The vocabulary will grow -- reading a content blob is a capability
/// the resource it covers does not exist yet -- and because
/// capabilities are rows of `TEXT` rather than columns or bits, that
/// growth is an insert rather than a migration.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Capability {
    /// Read the resources in the networks this token may reach.
    Read,
    /// Create, change and remove them.
    Write,
    /// Watch them: a snapshot and the stream of changes after it.
    Watch,
    /// The operator's operations, which are about the store rather
    /// than about any network in it.
    Admin,
}

impl Capability {
    /// Every capability, in the order a listing shows them, so that a
    /// caller enumerating them does not have to guess at the strings
    /// or at an order.
    pub const ALL: [Capability; 4] = [
        Capability::Read,
        Capability::Write,
        Capability::Watch,
        Capability::Admin,
    ];

    /// The capability as it is stored and as a consumer sees it.
    ///
    /// Lower case rather than the Rust spelling, for the same reason
    /// an event kind is: the value is in a database column and on a
    /// wire, and neither is a place to read a Rust identifier.
    pub fn as_str(self) -> &'static str {
        match self {
            Capability::Read => "read",
            Capability::Write => "write",
            Capability::Watch => "watch",
            Capability::Admin => "admin",
        }
    }

    /// The capability a stored string names.
    ///
    /// A value this code wrote always parses, the column being
    /// constrained to exactly these four. One that does not means
    /// something else has been writing the table, which is worth
    /// saying rather than reporting a permission of some unknown kind
    /// that every check would then have to decide what to do with.
    fn from_stored(value: &str) -> Result<Self> {
        Capability::ALL
            .into_iter()
            .find(|capability| capability.as_str() == value)
            .ok_or_else(|| Error::Malformed {
                detail: format!("a token of its own holds the capability {value:?}"),
            })
    }
}

impl fmt::Display for Capability {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.as_str())
    }
}

/// Which networks a token may reach.
///
/// The every-network form is a variant rather than an empty list or a
/// magic name, because a wildcard is typed and never defaulted: a
/// scope that forgot to say what it covered would otherwise cover
/// everything, and a sentinel name would collide with a real network
/// the day somebody names one `*`.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum TokenScope {
    /// Every network in the store, including the ones created after
    /// the token was minted. This is what the owning peer mints the
    /// first operator token with, and nothing else should need it.
    EveryNetwork,
    /// Exactly these networks, by name, and no others.
    ///
    /// The names need not exist. A scope is a statement about names
    /// rather than a reference to resources: the first token is
    /// minted before any network is created, so a token naming a
    /// network that is not there yet is the ordinary bootstrap order.
    Networks(Vec<String>),
}

impl TokenScope {
    /// Whether this scope reaches `network`.
    fn reaches(&self, network: &str) -> bool {
        match self {
            TokenScope::EveryNetwork => true,
            TokenScope::Networks(networks) => networks.iter().any(|name| name == network),
        }
    }

    /// Whether everything `inner` reaches is inside this scope.
    ///
    /// The one predicate behind every refusal in this module, so that
    /// minting a token, removing one and seeing one in a listing
    /// cannot come to disagree about what "inside my own scope"
    /// means.
    ///
    /// The every-network form is not a set of networks a narrower
    /// scope could happen to cover: it reaches networks that do not
    /// exist yet, so only the every-network form contains it.
    fn covers(&self, inner: &TokenScope) -> bool {
        match (self, inner) {
            (TokenScope::EveryNetwork, _) => true,
            (TokenScope::Networks(_), TokenScope::EveryNetwork) => false,
            (TokenScope::Networks(_), TokenScope::Networks(inner)) => {
                inner.iter().all(|network| self.reaches(network))
            }
        }
    }
}

/// A token as it stands, without its secret.
///
/// Returned by a listing and by a successful verification, and it is
/// what the layer above holds for the length of a connection. There
/// is no field for the secret, which is the structural half of
/// "returned in plaintext exactly once": a caller that wanted to log
/// or store what it was presented would have to have kept it itself.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Token {
    /// The token's identity, which is also what its writes are
    /// recorded against.
    pub id: TokenId,
    /// What an operator calls it in a listing. Not unique: two hosts
    /// running one consumer legitimately share a name.
    pub name: String,
    /// The networks it may reach.
    pub scope: TokenScope,
    /// What it may do in them, in [`Capability::ALL`]'s order so that
    /// a listing reads the same way every time.
    pub capabilities: Vec<Capability>,
    /// The actor that minted it, in the rendering
    /// [`Actor::as_recorded`] produces. A string rather than an
    /// [`Actor`] because nothing parses an actor back, and the minter
    /// may be a token that has since been removed.
    pub minted_by: String,
    /// When it was minted, in seconds since the Unix epoch.
    pub minted_at: i64,
    /// When it was last presented successfully, or `None` if it never
    /// has been. `None` is a different fact from a time at the start
    /// of the epoch, which is why it is not stamped at minting.
    pub last_used_at: Option<i64>,
}

impl Token {
    /// Whether this token may reach `network` at all.
    ///
    /// The decision is here rather than in whatever calls it so that
    /// there is one answer to it. A caller that compared the scope's
    /// fields itself would be a second implementation of the rule
    /// that a token never widens, in the layer least able to notice
    /// that it had got it wrong.
    pub fn may_reach(&self, network: &str) -> bool {
        self.scope.reaches(network)
    }

    /// Whether this token holds `capability`.
    pub fn holds(&self, capability: Capability) -> bool {
        self.capabilities.contains(&capability)
    }
}

/// A token and its secret, as a mint returns them.
///
/// The one and only time the secret exists outside the caller that
/// presented it. It is not stored, not logged, and not readable
/// again: a consumer that loses it is minted another, which is the
/// behaviour wanted of a credential.
#[derive(Clone, Debug)]
pub struct MintedToken {
    /// The token as it now stands.
    pub token: Token,
    /// The secret, in plaintext. Thirty-two bytes of randomness from
    /// the engine, as lower-case hex.
    pub secret: String,
}

/// Who is asking something of the token table.
///
/// Every operation on a token except presenting a secret is
/// authorised against who is asking as well as what they asked for,
/// so the caller is a parameter of each rather than something the
/// store is told about separately.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Caller {
    /// A local process connecting as the uid the daemon runs as, read
    /// from the kernel rather than claimed.
    ///
    /// It has no scope and no capabilities, so it may do anything
    /// here. That is what makes the first token possible without an
    /// initial password, a token file or a secret printed at startup
    /// -- which is the whole reason the exception exists.
    OwningPeer(u32),
    /// A token, which may act only downwards: a token whose scope is
    /// not inside its own is not its to mint, to remove or to see.
    Token(TokenId),
}

impl Caller {
    /// The actor a token minted by this caller is recorded against.
    fn as_actor(&self) -> Actor {
        match self {
            Caller::OwningPeer(uid) => Actor::Peer(*uid),
            Caller::Token(id) => Actor::Token(id.clone()),
        }
    }
}

/// The tokens this store holds.
///
/// Separate from [`crate::BindingStore`] for the reasons in this
/// module's own documentation: a token is store-global, its mutations
/// cannot be events, and its audit is its row. None of these methods
/// takes a network and none returns a cursor, which is why the gate
/// that checks the binding store's shape does not govern this trait
/// and says so.
///
/// Implementations are `Send + Sync` and every method takes `&self`,
/// as the binding store's do: a store is shared and the serialisation
/// of its writes is the implementation's business.
#[async_trait]
pub trait TokenStore: Send + Sync {
    /// Mint a token for `minter`, and return it with its secret.
    ///
    /// **The subset rule is enforced here**, not merely checked by
    /// whatever calls this. A token may grant only what it holds
    /// itself: a scope outside its own, or a capability it lacks, is
    /// refused. So is a mint by a token without `Admin`. An
    /// authorisation rule that lived only in the layer that calls
    /// this would be a rule the second caller skips -- and the second
    /// caller here is already foreseen, because the daemon that
    /// serves the socket is not the only thing that will link this
    /// crate.
    ///
    /// Without the rule, a token holding `Admin` in one network could
    /// mint itself an every-network token, which is the whole
    /// boundary defeated in one call.
    ///
    /// The owning peer has no scope, so it may mint anything. That is
    /// the bootstrap path and the only exception, and it applies to
    /// removing and listing as well.
    async fn mint(
        &self,
        minter: &Caller,
        name: &str,
        scope: &TokenScope,
        capabilities: &[Capability],
    ) -> Result<MintedToken>;

    /// Remove the token `id`, with its scope and its capabilities.
    ///
    /// **Scoped here, by the same rule as a mint**: a caller may
    /// remove a token whose scope is inside its own, and needs
    /// `Admin` to remove one at all. Removing a credential breaks
    /// whatever was using it, so a token holding `Admin` in one
    /// network taking away another network's consumer would reach
    /// across the boundary the scope draws -- and a rule checked only
    /// in the layer that calls this is one a second caller skips.
    ///
    /// A token the store does not have is reported as not found
    /// rather than quietly succeeding: a caller that believes it has
    /// revoked a credential and has not is the worst available
    /// outcome here.
    ///
    /// The writes the token made keep its id as their actor. The
    /// attribution outlives the credential deliberately -- "who moved
    /// this binding" is a question about the past, and a token
    /// removed this morning is still the answer to it.
    async fn delete(&self, caller: &Caller, id: &TokenId) -> Result<()>;

    /// Every token inside the caller's own scope, without its secret,
    /// by the time it was minted.
    ///
    /// **Filtered here**, on the same rule a removal uses, and
    /// filtered rather than refused. A network's name is its
    /// identifier, so a listing that showed a token scoped to a
    /// network the caller may not reach would say that the network
    /// exists, which is the same class of leak as answering a read
    /// outside a scope. `Admin` is needed to list at all.
    ///
    /// Oldest first, because this is read as a history of what has
    /// been handed out.
    async fn list(&self, caller: &Caller) -> Result<Vec<Token>>;

    /// The token whose secret is `secret`, if there is one, recording
    /// that it has been used.
    ///
    /// `None` rather than an error, because a secret nothing matches
    /// is not a failure of the store: the caller turns it into its
    /// own refusal, and an error would have to name what it could not
    /// find -- which here is the secret itself, in a message bound
    /// for a log.
    ///
    /// The verification and the stamping of the last-used time are
    /// one statement, so a token cannot be verified without the row
    /// recording it.
    async fn authenticate(&self, secret: &str) -> Result<Option<Token>>;
}

// ---------------------------------------------------------------------
// The statements.
//
// The same rule as every other module holding SQL in this crate: no
// type from `rusqlite` appears in a signature that leaves the crate,
// and nothing here is public. Unlike the others there is no network
// to scope by, which is the whole of what makes this a trait of its
// own, so there is no `Reading` and no guard: the questions asked
// here have no network for an answer to come from the wrong one of.
// ---------------------------------------------------------------------

/// The lower-case hex of `secret`'s SHA-256.
///
/// The one place in this crate that hashes anything. SQLite has no
/// digest function of its own, which is the entire reason a hashing
/// dependency exists here; the randomness still comes from the
/// engine, as the store's epoch does.
fn hashed(secret: &str) -> String {
    let digest = Sha256::digest(secret.as_bytes());

    let mut rendered = String::with_capacity(digest.len() * 2);
    for byte in digest.iter().copied() {
        rendered.push(hex_digit(byte >> 4));
        rendered.push(hex_digit(byte & 0x0f));
    }

    rendered
}

/// One hex digit, as the engine's own `hex()` would render it.
///
/// Arithmetic rather than an index into a table of digits, so that
/// there is no slice to be indexed out of: the only callers pass a
/// nibble, and a value above fifteen is unreachable rather than
/// bounds-checked.
fn hex_digit(nibble: u8) -> char {
    match nibble {
        0..=9 => char::from(b'0' + nibble),
        _ => char::from(b'a' + nibble - 10),
    }
}

/// Mint a token, enforcing that it grants no more than its minter
/// holds.
pub(crate) fn mint(
    conn: &mut Connection,
    clock: &dyn Clock,
    minter: &Caller,
    name: &str,
    scope: &TokenScope,
    capabilities: &[Capability],
) -> Result<MintedToken> {
    validate_name("token name", name)?;
    validate_request(scope, capabilities)?;

    let now = clock.unix_seconds();
    let minted_by = minter.as_actor().as_recorded();

    let transaction = conn
        .transaction()
        .map_err(storage("starting a transaction to mint a token"))?;

    // The subset check and the insert are in one transaction, so a
    // minter whose own token is removed while this runs cannot have
    // granted anything on the strength of what it used to hold.
    if let Caller::Token(id) = minter {
        let holder = read_token(&transaction, id)?.ok_or_else(|| Error::Unauthorised {
            action: "mint a token",
            detail: "the token asking for it no longer exists".to_owned(),
        })?;

        permit(&holder, scope, capabilities)?;
    }

    // Both random values come from the engine, which is the same
    // generator the store's epoch comes from, rather than from a
    // dependency of this crate's own.
    let (id, secret): (String, String) = transaction
        .query_row(
            "SELECT lower(hex(randomblob(16))), lower(hex(randomblob(32)))",
            [],
            |row| Ok((row.get(0)?, row.get(1)?)),
        )
        .map_err(storage("generating a token"))?;

    let all_networks = i64::from(matches!(scope, TokenScope::EveryNetwork));

    transaction
        .execute(
            "INSERT INTO token
                 (id, name, secret_sha256, all_networks, minted_by, minted_at, last_used_at)
             VALUES (?1, ?2, ?3, ?4, ?5, ?6, NULL)",
            params![id, name, hashed(&secret), all_networks, minted_by, now],
        )
        .map_err(storage("recording a token"))?;

    if let TokenScope::Networks(networks) = scope {
        for network in networks {
            transaction
                .execute(
                    "INSERT INTO token_network (token, network) VALUES (?1, ?2)",
                    params![id, network],
                )
                .map_err(storage("recording the networks a token may reach"))?;
        }
    }

    for capability in capabilities {
        transaction
            .execute(
                "INSERT OR IGNORE INTO token_capability (token, capability) VALUES (?1, ?2)",
                params![id, capability.as_str()],
            )
            .map_err(storage("recording what a token may do"))?;
    }

    transaction
        .commit()
        .map_err(storage("committing a token"))?;

    let mut ordered = capabilities.to_vec();
    order_capabilities(&mut ordered);
    ordered.dedup();

    Ok(MintedToken {
        token: Token {
            id: TokenId(id),
            name: name.to_owned(),
            scope: scope.clone(),
            capabilities: ordered,
            minted_by,
            minted_at: now,
            last_used_at: None,
        },
        // The plaintext, returned here and nowhere else ever again.
        secret,
    })
}

/// Refuse a request that would produce a token nothing could use.
///
/// Both halves are a mistake rather than a configuration: a scope
/// naming no network reaches nothing, and no capability does nothing,
/// and in each case the typed form for what the caller probably meant
/// is right there -- the every-network scope, or a capability.
fn validate_request(scope: &TokenScope, capabilities: &[Capability]) -> Result<()> {
    if let TokenScope::Networks(networks) = scope {
        if networks.is_empty() {
            return Err(Error::Invalid {
                what: "token scope",
                detail: "it names no network, so the token could reach nothing".to_owned(),
            });
        }

        for network in networks {
            validate_name("network name", network)?;
        }
    }

    if capabilities.is_empty() {
        return Err(Error::Invalid {
            what: "token",
            detail: "it would hold no capability, so it could do nothing".to_owned(),
        });
    }

    Ok(())
}

/// Refuse a mint that would grant more than the minting token holds.
///
/// Three refusals, and each names what was outside the minter's
/// reach rather than only that something was. The minter already
/// knows its own scope, so telling it which network it may not grant
/// leaks nothing, and it is the difference between a message an
/// operator can act on and one they have to guess at.
fn permit(holder: &Token, scope: &TokenScope, capabilities: &[Capability]) -> Result<()> {
    require_admin(holder, "mint a token")?;

    if !holder.scope.covers(scope) {
        return Err(Error::Unauthorised {
            action: "mint a token",
            detail: outside(holder, scope),
        });
    }

    for capability in capabilities {
        if !holder.holds(*capability) {
            return Err(Error::Unauthorised {
                action: "mint a token",
                detail: format!(
                    "the token {} does not hold the {capability} capability",
                    holder.id
                ),
            });
        }
    }

    Ok(())
}

/// Refuse a caller that does not hold the operator's capability.
///
/// Minting, removing and listing are the operator's own operations,
/// and `admin` is what they are gated on. Checked here rather than
/// only where the socket is served, because the subset rules below
/// are worth nothing if anything holding a token can reach the
/// operations they guard.
fn require_admin(holder: &Token, action: &'static str) -> Result<()> {
    if holder.holds(Capability::Admin) {
        return Ok(());
    }

    Err(Error::Unauthorised {
        action,
        detail: format!(
            "the token {} does not hold the {} capability",
            holder.id,
            Capability::Admin
        ),
    })
}

/// What was outside a caller's scope, as a sentence.
///
/// Named rather than reported as a bare refusal, for the reason
/// [`permit`] gives: the caller is told about its own scope or about
/// something it asked for, so there is nothing here it did not
/// already know.
fn outside(holder: &Token, scope: &TokenScope) -> String {
    match scope {
        TokenScope::EveryNetwork => format!(
            "the token {} is scoped to named networks, so every network is outside it",
            holder.id
        ),
        TokenScope::Networks(networks) => {
            match networks.iter().find(|network| !holder.may_reach(network)) {
                Some(network) => {
                    format!("the token {} cannot reach the network {network}", holder.id)
                }
                // Unreachable through `covers`, which is what every
                // caller asks first. Reported rather than claimed
                // impossible, because a refusal with no reason in it
                // is the one thing an operator cannot act on.
                None => format!("the token {} does not cover that scope", holder.id),
            }
        }
    }
}

/// Put capabilities in the order a listing shows them.
fn order_capabilities(capabilities: &mut [Capability]) {
    capabilities
        .sort_by_key(|capability| Capability::ALL.iter().position(|known| known == capability));
}

/// Remove a token and everything that hangs off it.
///
/// Scoped by the same rule a mint is: a caller may remove a token
/// whose scope is inside its own. Removing a credential breaks
/// whatever was using it, so a token holding `admin` in one network
/// taking away another network's consumer would be reaching across
/// exactly the boundary the scope draws.
///
/// The children go by the cascade on their own foreign keys, so a
/// half-removed token -- a credential with no capabilities, or a
/// scope with no credential -- is not a state this can leave behind.
pub(crate) fn delete(conn: &mut Connection, caller: &Caller, id: &TokenId) -> Result<()> {
    let transaction = conn
        .transaction()
        .map_err(storage("starting a transaction to remove a token"))?;

    // The check and the removal are one transaction, so a caller
    // whose own token is taken away while this runs cannot have
    // removed anything on the strength of what it used to hold.
    let target = read_token(&transaction, id)?.ok_or_else(|| Error::NotFound {
        kind: TOKEN,
        id: id.as_str().to_owned(),
    })?;

    if let Caller::Token(asking) = caller {
        let holder = read_token(&transaction, asking)?.ok_or_else(|| Error::Unauthorised {
            action: "remove a token",
            detail: "the token asking for it no longer exists".to_owned(),
        })?;

        require_admin(&holder, "remove a token")?;

        if !holder.scope.covers(&target.scope) {
            // The refusal says the scope is outside the caller's and
            // not that the token does not exist, because the caller
            // named an id it already had: there is nothing here it
            // could learn that it did not supply.
            return Err(Error::Unauthorised {
                action: "remove a token",
                detail: outside(&holder, &target.scope),
            });
        }
    }

    transaction
        .execute("DELETE FROM token WHERE id = ?1", params![id.as_str()])
        .map_err(storage("removing a token"))?;

    transaction
        .commit()
        .map_err(storage("committing the removal of a token"))?;

    Ok(())
}

/// Every token inside the caller's own scope, oldest first.
///
/// Filtered rather than refused, and filtered on the same rule a
/// removal uses. A network's name is its identifier, so a listing
/// that showed a token scoped to a network the caller may not reach
/// would say that the network exists -- which is the same class of
/// leak as answering a read outside a scope.
pub(crate) fn list(conn: &Connection, caller: &Caller) -> Result<Vec<Token>> {
    let scope = match caller {
        Caller::OwningPeer(_) => TokenScope::EveryNetwork,
        Caller::Token(asking) => {
            let holder = read_token(conn, asking)?.ok_or_else(|| Error::Unauthorised {
                action: "list the tokens",
                detail: "the token asking no longer exists".to_owned(),
            })?;

            require_admin(&holder, "list the tokens")?;

            holder.scope
        }
    };

    Ok(listed(conn)?
        .into_iter()
        .filter(|token| scope.covers(&token.scope))
        .collect())
}

/// Every token the store holds, oldest first.
fn listed(conn: &Connection) -> Result<Vec<Token>> {
    let ids: Vec<String> = {
        let mut statement = conn
            .prepare_cached("SELECT id FROM token ORDER BY minted_at, id")
            .map_err(storage("preparing a read of the tokens"))?;

        let rows = statement
            .query_map([], |row| row.get::<_, String>(0))
            .map_err(storage("reading the tokens"))?;

        let mut ids = Vec::new();
        for row in rows {
            ids.push(row.map_err(storage("reading a token"))?);
        }
        ids
    };

    let mut tokens = Vec::with_capacity(ids.len());
    for id in ids {
        // A token removed between the two reads is skipped rather
        // than reported as a token with no scope, which is a state no
        // token is ever in.
        if let Some(token) = read_token(conn, &TokenId(id))? {
            tokens.push(token);
        }
    }

    Ok(tokens)
}

/// Verify a presented secret and record that it was used.
///
/// The lookup and the stamping of the last-used time are in one
/// transaction, so there is no state in which a token was verified
/// and its use not recorded -- which matters because the row is the
/// whole of a token's audit trail and a credential whose last use is
/// missing is one nobody can say is dormant.
pub(crate) fn authenticate(
    conn: &mut Connection,
    clock: &dyn Clock,
    secret: &str,
) -> Result<Option<Token>> {
    let now = clock.unix_seconds();

    let transaction = conn
        .transaction()
        .map_err(storage("starting a transaction to verify a token"))?;

    // The presented secret is hashed and the hash is what is
    // compared, so the plaintext never reaches a comparison against
    // anything stored. The column is unique, so this answers with at
    // most one token structurally rather than by the width of the
    // random value alone.
    let id: Option<String> = transaction
        .query_row(
            "SELECT id FROM token WHERE secret_sha256 = ?1",
            params![hashed(secret)],
            |row| row.get(0),
        )
        .optional()
        .map_err(storage("verifying a token"))?;

    let token = match id {
        Some(id) => {
            transaction
                .execute(
                    "UPDATE token SET last_used_at = ?2 WHERE id = ?1",
                    params![id, now],
                )
                .map_err(storage("recording that a token was used"))?;

            read_token(&transaction, &TokenId(id))?
        }
        None => None,
    };

    transaction
        .commit()
        .map_err(storage("committing a token's use"))?;

    Ok(token)
}

/// One token, with its scope and its capabilities, or nothing.
///
/// The secret's hash is deliberately not selected. Nothing above this
/// module has any use for it, and a value that is never read cannot
/// be logged by accident.
fn read_token(conn: &Connection, id: &TokenId) -> Result<Option<Token>> {
    let found: Option<(String, i64, String, i64, Option<i64>)> = conn
        .query_row(
            "SELECT name, all_networks, minted_by, minted_at, last_used_at FROM token
             WHERE id = ?1",
            params![id.as_str()],
            |row| {
                Ok((
                    row.get(0)?,
                    row.get(1)?,
                    row.get(2)?,
                    row.get(3)?,
                    row.get(4)?,
                ))
            },
        )
        .optional()
        .map_err(storage("reading a token"))?;

    let Some((name, all_networks, minted_by, minted_at, last_used_at)) = found else {
        return Ok(None);
    };

    let scope = if all_networks == 1 {
        TokenScope::EveryNetwork
    } else {
        TokenScope::Networks(token_networks(conn, id)?)
    };

    Ok(Some(Token {
        id: id.clone(),
        name,
        scope,
        capabilities: token_capabilities(conn, id)?,
        minted_by,
        minted_at,
        last_used_at,
    }))
}

/// The networks one token names.
fn token_networks(conn: &Connection, id: &TokenId) -> Result<Vec<String>> {
    let mut statement = conn
        .prepare_cached("SELECT network FROM token_network WHERE token = ?1 ORDER BY network")
        .map_err(storage("preparing a read of a token's networks"))?;

    let rows = statement
        .query_map(params![id.as_str()], |row| row.get::<_, String>(0))
        .map_err(storage("reading a token's networks"))?;

    let mut networks = Vec::new();
    for row in rows {
        networks.push(row.map_err(storage("reading a network a token may reach"))?);
    }

    Ok(networks)
}

/// What one token may do.
fn token_capabilities(conn: &Connection, id: &TokenId) -> Result<Vec<Capability>> {
    let mut statement = conn
        .prepare_cached("SELECT capability FROM token_capability WHERE token = ?1")
        .map_err(storage("preparing a read of a token's capabilities"))?;

    let rows = statement
        .query_map(params![id.as_str()], |row| row.get::<_, String>(0))
        .map_err(storage("reading a token's capabilities"))?;

    let mut capabilities = Vec::new();
    for row in rows {
        capabilities.push(Capability::from_stored(
            &row.map_err(storage("reading a capability"))?,
        )?);
    }

    order_capabilities(&mut capabilities);

    Ok(capabilities)
}

#[cfg(test)]
mod tests {
    use super::{Capability, hashed, order_capabilities};

    #[test]
    fn a_secret_hashes_to_the_digest_the_engine_would_have_written() {
        // The known-answer test for SHA-256 of the empty string. It
        // is here because the stored value has to be the digest and
        // not some other function of the secret: a mistake in the
        // rendering would still verify, every presentation being
        // hashed the same wrong way, and would only show up against
        // another implementation.
        assert_eq!(
            hashed(""),
            "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
        );
        assert_eq!(hashed("").len(), 64);
    }

    #[test]
    fn capabilities_are_listed_in_one_order_however_they_arrive() {
        let mut capabilities = vec![
            Capability::Admin,
            Capability::Read,
            Capability::Watch,
            Capability::Write,
        ];
        order_capabilities(&mut capabilities);

        assert_eq!(capabilities, Capability::ALL.to_vec());
    }
}
